const DICTS: Record<Lang, Dict> = { 'zh-CN': zhCN, 'zh-TW': zhTW, en };

let current: Lang = 'zh-CN';
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function isLang(value: unknown): value is Lang {
  return value === 'zh-CN' || value === 'zh-TW' || value === 'en';
}

/** 切换语言并通知所有订阅者（持久化由调用方负责） */
export function setLang(next: Lang): void {
  if (!isLang(next) || next === current) return;
  current = next;
  document.documentElement.lang = next;
  for (const fn of listeners) fn();
}

/** 取文案；本字典缺 key 时查主进程那份（服务商说明等共用），再回落简中，最后显示 key */
export function t(key: string, lang: Lang = current, vars?: Record<string, string>): string {
  const text =
    DICTS[lang]?.[key] ?? MAIN_DICTS[lang]?.[key] ?? zhCN[key] ?? MAIN_DICTS['zh-CN'][key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => vars[name] ?? match);
}

/** 订阅当前语言：语言一变，组件立即重渲染 */
export function useLang(): [Lang, (next: Lang) => void] {
  const [lang, setLocal] = useState<Lang>(current);

  useEffect(() => {
    const sync = (): void => setLocal(current);
    listeners.add(sync);
    // 订阅时补一次同步，避免在订阅前就切换过语言
    sync();
    return () => {
      listeners.delete(sync);
    };
  }, []);

  return [lang, setLang];
}
